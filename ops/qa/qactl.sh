seed_tool() {
    load_env
    local mounts=(-v "$QA_OPS_DIR/qa_seed.py:/qa/qa_seed.py:ro" -v "$PERSONAS_FILE:/qa/personas.json:ro"
                  -v "$CRED_FILE:/qa/credentials.env:ro")
    [ -d "$CONTENT" ] && mounts+=(-v "$CONTENT:/qa/content:ro")
    [ -d "$EXAMPLES" ] && mounts+=(-v "$EXAMPLES:/qa/examples:ro")
    qa_compose run --rm --no-deps -T "${mounts[@]}" \
        -e PYTHONPATH=/home/worker/computor-backend/src -e QA_API_URL=http://uvicorn:8000 \
        -e QA_PUBLIC_ORIGIN -e TESTING_WORKER_TOKEN -e QA_DEPLOYED_VSIX uvicorn python /qa/qa_seed.py "$@"
}

# Re-uploaded examples keep their version ids, and the testing worker caches
# each version set by id for good (tasks/temporal_student_testing.py), so a
# re-run would keep grading against the files it fetched before.
seed_content() {
    seed_tool content
    qa_compose exec -T temporal-worker-testing \
        sh -c 'rm -rf "${EXAMPLE_CACHE_DIR:-/tmp/examples}/by-version"' || true
}

# Workspace image and template. A deployed VSIX must be in the template
# directory for the image build and out of it for the push (Coder caps the
# template archive at 1 MiB), so that case builds and pushes separately.
seed_templates() {
    load_env
    local tdir="$DATA/coder/templates/vscode"
    if [ -n "${QA_DEPLOYED_VSIX:-}" ]; then
        apply_vsix_to_template
        seed_tool templates-build
        rm -f "$tdir/qa-extension.vsix"
    fi
    seed_tool templates
}

cmd_up() {
    ensure_state
    ensure_source
    load_env
    stage_runtime_files
    images_present || build_images
    log "starting the stack"
    start_services
    wait_healthy uvicorn 600
    keycloak_setup
    if [ ! -f "$QA_HOME/.seeded" ]; then
        cmd_seed
    fi
    cmd_status
}

cmd_seed() {
    ensure_content
    local out
    out=$(seed_tool baseline)
    printf '%s\n' "$out" | grep -v '^QA_[A-Z_]*_API_TOKEN=' || true
    # New API tokens go to the private credentials file only.
    printf '%s\n' "$out" | grep '^QA_[A-Z_]*_API_TOKEN=' >> "$CRED_FILE" || true
    seed_content
    seed_templates
    seed_tool returning
    touch "$QA_HOME/.seeded"
}

ensure_content() {
    load_env
    [ -d "$CONTENT" ] || fetch_content "${QA_DEPLOYED_CONTENT_REF:-main}"
    [ -d "$EXAMPLES" ] || log "no examples package (deploy --examples FILE): test runs of the examples will error"
}

fetch_content() {
    local ref=$1 tmp
    tmp=$(mktemp -d "$QA_HOME/.content.XXXXXX")
    log "downloading data-science-python at $ref"
    curl -fsSL "$QA_CONTENT_REPO_URL/archive/$ref.tar.gz" | tar -xz -C "$tmp" --strip-components=1
    rm -rf "$CONTENT"
    mkdir -p "$(dirname "$CONTENT")"
    mv "$tmp" "$CONTENT"
    record_deployed QA_DEPLOYED_CONTENT_REF "$ref"
}

# The runnable examples, as computor.at has them: the python/ directory of
# GitLab codeability/development/examples with test.yaml, localTests and the
# full meta.yaml (the public mirror has none of them). The repository is
# private, so the archive is fetched where GitLab credentials are
# (ops/qa/fetch_examples.sh) and only the file comes to the QA host. GitLab
# names the top directory examples-<ref>-<commit>[-python].
install_examples() {
    local archive=$1 tmp top commit
    [ -f "$archive" ] || die "no such examples archive: $archive"
    top=$(tar -tzf "$archive" | sed -n 1p | cut -d/ -f1)
    commit=$(grep -oE '[0-9a-f]{40}' <<< "$top" | tail -n 1 || true)
    [[ "$commit" =~ ^[0-9a-f]{40}$ ]] || die "$archive is not a GitLab archive of the examples (top directory $top)"
    tmp=$(mktemp -d "$QA_HOME/.examples.XXXXXX")
    tar -xzf "$archive" -C "$tmp" --strip-components=2 "$top/python"
    [ -n "$(find "$tmp" -mindepth 2 -maxdepth 2 -name test.yaml -print -quit)" ] \
        || die "$archive has no python/<example>/test.yaml"
    rm -rf "$EXAMPLES"
    mkdir -p "$(dirname "$EXAMPLES")"
    mv "$tmp" "$EXAMPLES"
    record_deployed QA_DEPLOYED_EXAMPLES_REF "${commit:0:12}"
    log "examples package ${commit:0:12}: $(find "$EXAMPLES" -mindepth 1 -maxdepth 1 -type d | wc -l) examples"
}

cmd_down() {
    load_env
    qa_compose down --remove-orphans
}

cmd_reset() {
    load_env
    log "removing the stack and all of its state (synthetic data only)"
    remove_workspaces
    qa_compose down --remove-orphans --volumes || true
    # Files below data/ belong to container users; delete them from a container.
    docker run --rm -v "$QA_HOME:/qa" alpine@sha256:294b683cb724975bec92580e1e685676bd4b50bda910ddb8c51d4cabeaec77e6 \
        sh -c 'rm -rf /qa/data /qa/keycloak-import /qa/.seeded'
    sed -i '/^QA_[A-Z_]*_API_TOKEN=/d' "$CRED_FILE" 2>/dev/null || true
    cmd_up
}

# Workspace containers and their volumes are created by Coder's Terraform,
# outside Compose. Only containers on the QA workspace bridges are touched.
remove_workspaces() {
    local ids="" net volumes=""
    for net in "$CODER_WORKSPACE_NETWORK" "$CODER_WORKSPACE_NETWORK_OFFLINE"; do
        ids="$ids $(docker ps -aq --filter "network=$net" --filter "label=computor.ingress=workspace")"
    done
    if [ -n "${ids// /}" ]; then
        # shellcheck disable=SC2086
        volumes=$(docker inspect -f '{{range .Mounts}}{{if .Name}}{{.Name}} {{end}}{{end}}' $ids)
        # shellcheck disable=SC2086
        docker rm -f $ids >/dev/null
        # shellcheck disable=SC2086
        [ -n "${volumes// /}" ] && docker volume rm -f $volumes >/dev/null
    fi
    for net in "$CODER_WORKSPACE_NETWORK" "$CODER_WORKSPACE_NETWORK_OFFLINE"; do
        docker network rm "$net" >/dev/null 2>&1 || true
    done
}

cmd_deploy() {
    local backend_ref="" vsix="" content_ref="" examples=""
    while [ $# -gt 0 ]; do
        case "$1" in
            --backend-ref) backend_ref=$2; shift 2 ;;
            --vsix) vsix=$2; shift 2 ;;
            --content-ref) content_ref=$2; shift 2 ;;
            --examples) examples=$2; shift 2 ;;
            *) die "unknown deploy option: $1" ;;
        esac
    done
    ensure_state
    ensure_source
    load_env
    if [ -n "$backend_ref" ]; then
        # A reader pin from cmd_reader belongs to the previous ref.
        git -C "$SRC" checkout -q -- computor-web/learning-source.json
        sed -i '/^QA_DEPLOYED_READER_REF=/d' "$DEPLOYED_FILE"
        unset QA_DEPLOYED_READER_REF
        git -C "$SRC" fetch -q origin
        git -C "$SRC" checkout -q --detach "$backend_ref" 2>/dev/null \
            || git -C "$SRC" checkout -q --detach "origin/$backend_ref"
        record_deployed QA_DEPLOYED_BACKEND_REF "$backend_ref"
        log "backend at $(git -C "$SRC" rev-parse HEAD) ($backend_ref)"
    fi
    if [ "$vsix" = none ]; then
        # Back to the extension the template builds from git. The registry
        # versions stay yanked until the next reset.
        rm -f "$QA_HOME/vsix/computor.vsix"
        sed -i '/^QA_DEPLOYED_VSIX=/d' "$DEPLOYED_FILE"
        unset QA_DEPLOYED_VSIX
    elif [ -n "$vsix" ]; then
        [ -f "$vsix" ] || die "no such VSIX: $vsix"
        mkdir -p "$QA_HOME/vsix"
        install -m 0644 "$vsix" "$QA_HOME/vsix/computor.vsix"
        record_deployed QA_DEPLOYED_VSIX "$(basename "$vsix") sha256:$(sha256sum "$vsix" | cut -d' ' -f1)"
    fi
    load_env
    stage_runtime_files
    if [ -n "$backend_ref" ] || ! images_present; then
        build_images
    fi
    if [ -n "$content_ref" ] || [ -n "$examples" ]; then
        # Courses are imported into a fresh baseline: a release is not
        # re-applied onto courses that already have learners. Updating a
        # running course is the lecturer's job (README: course update rehearsal).
        [ -z "$examples" ] || install_examples "$examples"
        [ -z "$content_ref" ] || fetch_content "$content_ref"
        cmd_reset
        return
    fi
    start_services
    wait_healthy uvicorn 600
    keycloak_setup
    if [ -n "$vsix" ] || [ -n "$backend_ref" ]; then
        seed_templates
    fi
    cmd_status
}

# computor.at's /learn reader is a snapshot of the public mirror pinned in
# computor-web/learning-source.json and baked into the web image; publishing a
# new mirror revision there is a pin change plus a web redeploy. This does the
# same on the deployed worktree: pin REF, rebuild and restart the web only.
cmd_reader() {
    local ref="" commit sum
    while [ $# -gt 0 ]; do
        case "$1" in
            --content-ref) ref=$2; shift 2 ;;
            *) die "unknown reader option: $1" ;;
        esac
    done
    [ -n "$ref" ] || die "usage: qactl.sh reader --content-ref REF"
    ensure_state
    ensure_source
    load_env
    if [[ "$ref" =~ ^[0-9a-f]{40}$ ]]; then
        commit=$ref
    else
        commit=$(git ls-remote "$QA_CONTENT_REPO_URL" "refs/heads/$ref" "refs/tags/$ref" | head -n 1 | cut -f1)
        [ -n "$commit" ] || die "no branch or tag $ref in $QA_CONTENT_REPO_URL"
    fi
    sum=$(curl -fsSL "https://codeload.github.com/computor-org/data-science-python/tar.gz/$commit" | sha256sum | cut -d' ' -f1)
    printf '{\n  "repository": "computor-org/data-science-python",\n  "commit": "%s",\n  "archive_sha256": "%s"\n}\n' \
        "$commit" "$sum" > "$SRC/computor-web/learning-source.json"
    log "reader pinned to data-science-python $commit ($ref); rebuilding the web"
    # The sidebar shows this commit (docker-compose.web.yaml); without it "dev".
    GIT_COMMIT=$(git -C "$SRC" rev-parse HEAD) qa_compose build frontend
    qa_compose up -d --no-deps frontend
    record_deployed QA_DEPLOYED_READER_REF "$ref ${commit:0:12}"
}

cmd_status() {
    load_env
    qa_compose ps --format 'table {{.Name}}\t{{.Status}}'
    cat <<EOF

Backend ref:  ${QA_DEPLOYED_BACKEND_REF:-?} ($(git -C "$SRC" rev-parse --short HEAD 2>/dev/null || echo none))
Content ref:  ${QA_DEPLOYED_CONTENT_REF:-?}
Examples:     ${QA_DEPLOYED_EXAMPLES_REF:-none (public mirror only: test runs error)}
Reader pin:   ${QA_DEPLOYED_READER_REF:-as in the backend ref}
VSIX:         ${QA_DEPLOYED_VSIX:-built from computor-vscode main by the template}
Web:          $QA_PUBLIC_ORIGIN/
Keycloak:     $QA_PUBLIC_ORIGIN/auth/  (admin console realm master: $KEYCLOAK_ADMIN)
Mailpit:      http://127.0.0.1:$QA_MAILPIT_PORT/  API http://127.0.0.1:$QA_MAILPIT_PORT/api/v1/messages
Credentials:  $CRED_FILE
EOF
    cmd_tunnel
}

cmd_tunnel() {
    load_env
    echo "Tunnel:       ssh -N -L $QA_PORT:127.0.0.1:$QA_PORT -L $QA_MAILPIT_PORT:127.0.0.1:$QA_MAILPIT_PORT $(hostname -s)"
}

main() {
    local cmd=${1:-}
    [ $# -gt 0 ] && shift
    case "$cmd" in
        up) cmd_up ;;
        down) cmd_down ;;
        reset) cmd_reset ;;
        seed)
            ensure_state; load_env
            if [ "${1:-}" = templates ]; then seed_templates
            elif [ "${1:-}" = content ]; then ensure_content; seed_content
            elif [ $# -gt 0 ]; then ensure_content; seed_tool "$1"
            else cmd_seed; fi ;;
        deploy) cmd_deploy "$@" ;;
        reader) cmd_reader "$@" ;;
        status) cmd_status ;;
        tunnel) cmd_tunnel ;;
        compose) load_env; qa_compose "$@" ;;
        *) sed -n '2,30p' "$0"; [ -z "$cmd" ] || exit 2 ;;
    esac
}

# One line: bash reads a script while it runs, so a checkout updated during a
# long deploy would otherwise go on executing whatever the new file holds
# after this point ("return: can only `return' from a function").
main "$@"; exit
