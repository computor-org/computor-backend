# With --vsix, the deployed vscode template installs that file instead of
# building the extension from git. Only the deployed copy changes.
apply_vsix_to_template() {
    local tdir="$DATA/coder/templates/vscode"
    [ -n "${QA_DEPLOYED_VSIX:-}" ] && [ -f "$QA_HOME/vsix/computor.vsix" ] || return 0
    cp "$QA_HOME/vsix/computor.vsix" "$tdir/qa-extension.vsix"
    python3 - "$tdir/Dockerfile" <<'PY'
import re, sys
path = sys.argv[1]
text = open(path).read()
if "# Stage 1: Build VSIX extension" not in text:
    sys.exit(0)  # already replaced
start = text.index("# Stage 1: Build VSIX extension")
start = text.rfind("# ====", 0, start)
end = text.index("# Stage 2:")
end = text.rfind("# ====", 0, end)
stage = ("# QA: the VSIX given to qactl.sh deploy --vsix replaces the git build.\n"
         "FROM scratch AS vsix-builder\n"
         "COPY qa-extension.vsix /tmp/extension.vsix\n\n")
open(path, "w").write(text[:start] + stage + text[end:])
PY
    log "workspace template uses $QA_DEPLOYED_VSIX"
}

# --------------------------------------------------------------- images ----

build_images() {
    load_env
    local commit branch built
    commit=$(git -C "$SRC" rev-parse HEAD)
    branch=$(git -C "$SRC" rev-parse --abbrev-ref HEAD)
    built=$(date -u +%Y-%m-%dT%H:%M:%SZ)
    export GIT_COMMIT="$commit"
    log "building qa images from backend $commit"
    (cd "$SRC" && BUILDX_BUILDER=default docker build -q -f docker/base/Dockerfile -t "$QA_BASE_IMAGE" \
        --build-arg GIT_COMMIT="$commit" --build-arg GIT_BRANCH="$branch" \
        --build-arg BUILD_TIME="$built" .)
    # Content-addressed like computor.sh: rebuilt only when their inputs move.
    # shellcheck disable=SC1091
    (export BUILDX_BUILDER=default; source "$SRC/ops/lib/common.sh"
     build_base_image testing-runtimes "$QA_TESTING_RUNTIMES_IMAGE" docker/testing-runtimes/Dockerfile .
     build_base_image coder-runtime "$QA_CODER_RUNTIME_IMAGE" docker/coder-runtime/Dockerfile .
     # Workspace images are built by the coder worker FROM this shared tag
     # (ops/coder/templates/*/Dockerfile); same inputs give the same image.
     build_base_image code-server computor-code-server:latest \
         docker/code-server-base/Dockerfile docker/code-server-base)
    qa_compose build uvicorn temporal-worker temporal-worker-testing \
        temporal-worker-coder frontend
}

