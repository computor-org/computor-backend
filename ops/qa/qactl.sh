#!/usr/bin/env bash
# QA stack controller (computor-org/issues#529).
#
# Runs one isolated Computor stack (web, API, workers, Keycloak, Forgejo,
# Coder, Mailpit) beside whatever else the host runs: containers named qa-*,
# Compose project "qa", its own networks and bind-mounted state under
# QA_HOME, every port on 127.0.0.1, CPU and memory limits per service.
# See ops/qa/README.md for usage.
#
#   qactl.sh up                 create state if missing, build missing images, start, seed
#   qactl.sh down               stop the stack, keep its state
#   qactl.sh reset              wipe all state, start fresh, import content, seed
#   qactl.sh seed [STEP]        (re)apply the baseline, or one step of ops/qa/qa_seed.py
#   qactl.sh deploy [--backend-ref REF] [--vsix FILE|none] [--content-ref REF] [--examples FILE]
#     --backend-ref/--vsix preserve state; either --content-ref or --examples
#     wipes ALL QA state and imports a fresh synthetic baseline.
#   qactl.sh reader --content-ref REF   pin the public /learn reader to a mirror ref
#   qactl.sh status             containers, health and URLs
#   qactl.sh tunnel             the ssh command that reaches the stack
#   qactl.sh compose ARGS...    docker compose with the stack's files and env
#
# State (QA_HOME, default /mnt/storage/computor-qa):
#   qa.env            compose environment with generated secrets (0600)
#   credentials.env   persona logins, admin API token, Mailpit URL (0600)
#   personas.json     the same personas for the realm import (0600)
#   data/             SYSTEM_DEPLOYMENT_PATH of the stack
#   src/backend       detached worktree of the deployed backend ref
#   src/content       data-science-python at the deployed content ref
#   src/examples      the runnable examples package (python/ of GitLab
#                     codeability/development/examples), from deploy --examples
#   vsix/             the VSIX baked into the workspace image, if any
#   deployed.env      backend/VSIX and baseline import refs; excludes lecturer edits
set -euo pipefail

QA_OPS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CONTROLLER_ROOT="$(cd "$QA_OPS_DIR/../.." && pwd)"
QA_HOME="${QA_HOME:-/mnt/storage/computor-qa}"
QA_PROJECT="qa"
QA_PREFIX="qa-"
# Main backend checkout that the deployed worktree is created from.
QA_BACKEND_REPO="${QA_BACKEND_REPO:-$(git -C "$CONTROLLER_ROOT" rev-parse --path-format=absolute --git-common-dir 2>/dev/null | sed 's#/.git$##')}"
QA_CONTENT_REPO_URL="${QA_CONTENT_REPO_URL:-https://github.com/computor-org/data-science-python}"
# Coder pushes and pulls workspace images through localhost:5000 on the
# Docker host; the templates and the worker's socket proxy hardcode it.
QA_REGISTRY_PORT=5000

ENV_FILE="$QA_HOME/qa.env"
CRED_FILE="$QA_HOME/credentials.env"
PERSONAS_FILE="$QA_HOME/personas.json"
PERSONAL_FILE="$QA_HOME/personal.env"
DEPLOYED_FILE="$QA_HOME/deployed.env"
DATA="$QA_HOME/data"
SRC="$QA_HOME/src/backend"
CONTENT="$QA_HOME/src/content"
EXAMPLES="$QA_HOME/src/examples"

log() { printf '[qactl] %s\n' "$*"; }
die() { printf '[qactl] ERROR: %s\n' "$*" >&2; exit 1; }

secret() { openssl rand -hex "${1:-24}"; }
# TOKEN_SECRET is a Fernet key (utils/encryption.py): 32 url-safe base64 bytes.

load_env() {
    [ -f "$ENV_FILE" ] || die "no $ENV_FILE yet; run: qactl.sh up"
    set -a
    # shellcheck disable=SC1090
    . "$ENV_FILE"
    # shellcheck disable=SC1090
    [ -f "$DEPLOYED_FILE" ] && . "$DEPLOYED_FILE"
    set +a
}

compose_files() {
    local d="$SRC/ops/docker"
    printf -- '-f %s ' \
        "$d/docker-compose.base.yaml" "$d/docker-compose.prod.yaml" \
        "$d/docker-compose.web.yaml" "$d/docker-compose.preview.yaml" \
        "$d/docker-compose.preview-state.yaml" "$d/docker-compose.forgejo.yaml" \
        "$d/docker-compose.forgejo-keycloak.yaml" "$d/docker-compose.coder.yaml" \
        "$QA_OPS_DIR/docker-compose.qa.yaml"
}

qa_compose() {
    # The docker driver builder: only it sees the local qa-computor-* base
    # images that additional_contexts names (a docker-container builder,
    # possibly the host's current one, would try to pull them).
    # shellcheck disable=SC2046
    BUILDX_BUILDER=default QA_SRC_DIR="$SRC" docker compose --project-name "$QA_PROJECT" --project-directory "$SRC/ops/docker" \
        --env-file "$ENV_FILE" $(compose_files) "$@"
}

