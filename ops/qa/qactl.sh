# Adds every missing agent persona and keeps existing ones (and their
# passwords), so a persona added later reaches an existing stack.
# Subshell body: its umask 077 must not leak into later checkouts/builds.
write_personas() (
    local admin_password
    admin_password=$(sed -n 's/^API_ADMIN_PASSWORD=//p' "$ENV_FILE")
    umask 077
    python3 - "$PERSONAS_FILE" "$admin_password" <<'PY'
import json, os, secrets, sys, uuid
path, admin_pw = sys.argv[1:]
ns = uuid.UUID("0d4c1d1e-5a29-4c6f-9f53-2b5a0c0e0529")
def persona(key, username, email, given, family, pw, role, groups=()):
    return {"key": key, "username": username, "email": email, "given_name": given,
            "family_name": family, "password": pw or secrets.token_hex(12), "system_role": role,
            "keycloak_id": str(uuid.uuid5(ns, username)), "groups": list(groups)}
wanted = [
    persona("admin", "qa-admin", "qa-admin@example.com", "Ada", "Admin", admin_pw, "_admin",
            ["/administrators"]),
    persona("lecturer", "qa-lecturer", "qa-lecturer@example.com", "Lukas", "Lehrer", None, None),
    persona("returning", "qa-returning", "qa-returning@example.com", "Rita", "Wiederkehr",
            None, None),
    persona("second", "qa-second", "qa-second@example.com", "Sami", "Zweiter", None, None),
]
personas = json.load(open(path)) if os.path.exists(path) else []
keys = {p["key"] for p in personas}
personas += [p for p in wanted if p["key"] not in keys]
with open(path, "w", encoding="utf-8") as fh:
    json.dump(personas, fh, indent=2)
PY
)

# A human tester's own account, kept apart from the agents' personas. It is
# defined only in the private file QA_HOME/personal.env (mode 0600, never in
# git) with QA_PERSONAL_USERNAME, QA_PERSONAL_EMAIL and QA_PERSONAL_PASSWORD,
# and it is merged into personas.json on every run, so a reset recreates it.
# Subshell body: its umask 077 must not leak into later checkouts/builds.
merge_personal_persona() (
    [ -f "$PERSONAL_FILE" ] || exit 0
    [ "$(stat -c %a "$PERSONAL_FILE")" = 600 ] || die "$PERSONAL_FILE must have mode 0600"
    umask 077
    python3 - "$PERSONAS_FILE" "$PERSONAL_FILE" <<'PY'
import json, sys, uuid
path, personal = sys.argv[1:]
env = {}
for line in open(personal, encoding="utf-8"):
    line = line.strip()
    if line and not line.startswith("#") and "=" in line:
        key, value = line.split("=", 1)
        env[key.strip()] = value.strip().strip('"')
username = env["QA_PERSONAL_USERNAME"]
ns = uuid.UUID("0d4c1d1e-5a29-4c6f-9f53-2b5a0c0e0529")
entry = {"key": "personal", "username": username, "email": env["QA_PERSONAL_EMAIL"],
         "given_name": env.get("QA_PERSONAL_GIVEN_NAME", "Personal"),
         "family_name": env.get("QA_PERSONAL_FAMILY_NAME", "Tester"),
         "password": env["QA_PERSONAL_PASSWORD"], "system_role": None,
         "keycloak_id": str(uuid.uuid5(ns, username)), "groups": []}
personas = [p for p in json.load(open(path)) if p["key"] != "personal"] + [entry]
with open(path, "w", encoding="utf-8") as fh:
    json.dump(personas, fh, indent=2)
PY
)

# Subshell body: its umask 077 must not leak into later checkouts/builds.
write_credentials() (
    load_env
    umask 077
    python3 - "$PERSONAS_FILE" "$CRED_FILE" <<PY
import json, sys
personas = json.load(open(sys.argv[1]))
lines = ["# QA stack credentials (synthetic accounts only). Generated by qactl.sh.",
         "QA_WEB_URL=$QA_PUBLIC_ORIGIN",
         "QA_MAILPIT_API=http://127.0.0.1:$QA_MAILPIT_PORT/api/v1",
         "QA_KEYCLOAK_ADMIN=$KEYCLOAK_ADMIN",
         "QA_KEYCLOAK_ADMIN_PASSWORD=$KEYCLOAK_ADMIN_PASSWORD"]
for p in personas:
    k = p["key"].upper()
    lines += [f"QA_{k}_USERNAME={p['username']}", f"QA_{k}_EMAIL={p['email']}",
              f"QA_{k}_PASSWORD={p['password']}"]
with open(sys.argv[2] + ".tmp", "w") as fh:
    fh.write("\n".join(lines) + "\n")
PY
    # API tokens are added by the seed (cmd_seed) and kept across rewrites.
    if [ -f "$CRED_FILE" ]; then
        grep '^QA_[A-Z_]*_API_TOKEN=' "$CRED_FILE" >> "$CRED_FILE.tmp" || true
    fi
    mv "$CRED_FILE.tmp" "$CRED_FILE"
)

ensure_state() {
    command -v python3 >/dev/null || die "python3 is required on the host"
    mkdir -p "$QA_HOME"
    chmod 700 "$QA_HOME"
    [ -f "$ENV_FILE" ] || { log "generating $ENV_FILE"; write_env; }
    write_personas
    merge_personal_persona
    write_credentials
    for d in postgres temporal-postgres redis redis-data minio/data \
             shared/documents shared/courses shared/course-contents shared/defaults \
             shared/repositories traefik/dynamic deployments keycloak-db \
             keycloak/providers forgejo/postgres forgejo/data coder/home \
             coder/registry coder/templates coder-postgres coder-hostops \
             workspace-ingress/dynamic analytics; do
        mkdir -p "$DATA/$d"
    done
    chmod 777 "$DATA/coder/home"
    mkdir -p "$QA_HOME/keycloak-import"
    chmod 755 "$QA_HOME/keycloak-import"
}

ensure_source() {
    if [ ! -e "$SRC/.git" ]; then
        [ -n "$QA_BACKEND_REPO" ] && [ -d "$QA_BACKEND_REPO/.git" ] \
            || die "set QA_BACKEND_REPO to the main computor-backend checkout"
        mkdir -p "$(dirname "$SRC")"
        git -C "$QA_BACKEND_REPO" fetch -q origin
        git -C "$QA_BACKEND_REPO" worktree add --detach "$SRC" "${QA_BACKEND_REF:-origin/main}"
        record_deployed QA_DEPLOYED_BACKEND_REF "${QA_BACKEND_REF:-origin/main}"
    fi
}

record_deployed() {
    local key=$1 value=$2
    touch "$DEPLOYED_FILE"
    grep -v "^$key=" "$DEPLOYED_FILE" > "$DEPLOYED_FILE.tmp" || true
    printf '%s=%q\n' "$key" "$value" >> "$DEPLOYED_FILE.tmp"
    mv "$DEPLOYED_FILE.tmp" "$DEPLOYED_FILE"
}

