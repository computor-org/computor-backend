"""Top-level README generation for the student template repository."""
import logging
import os

from sqlalchemy.orm import Session, joinedload

from ...business_logic.localization import localized_text

logger = logging.getLogger(__name__)

# The template is shared by every learner of the course, so it cannot follow
# one reading language: German first, then English.
README_LANGUAGES = ("de", "en")

_README_TEXT = {
    "de": {
        "heading": "{course} – Aufgabenvorlage",
        "intro": "Dieses Repository enthält {count} Aufgaben aus {course}.",
        "structure": "Aufbau",
        "columns": "| Kursabschnitt | Verzeichnis | Titel | Version |",
        "none": "*Es sind noch keine Aufgaben veröffentlicht.*",
        "instructions": "Anleitung",
        "instructions_text": "Jede Aufgabe liegt in einem eigenen Verzeichnis. Öffne es und folge der Anleitung in der README-Datei dieses Verzeichnisses.",
        "submission": "Abgabe",
        "submission_text": "Reiche jede Aufgabe so ein, wie es dein Kurs vorsieht.",
        "generated": "*Von Computor erstellt*",
    },
    "en": {
        "heading": "{course} – Student Template",
        "intro": "This repository contains {count} assignments for {course}.",
        "structure": "Assignment Structure",
        "columns": "| Content Path | Assignment Directory | Title | Version |",
        "none": "*No assignments deployed yet.*",
        "instructions": "Instructions",
        "instructions_text": "Each assignment is in its own directory. Navigate to the assignment directory and follow the instructions in its README file.",
        "submission": "Submission",
        "submission_text": "Follow your course submission guidelines for each assignment.",
        "generated": "*Generated by Computor*",
    },
}


def _title(obj, lang: str) -> str:
    return localized_text(getattr(obj, "title_i18n", None), lang, getattr(obj, "title", None)) or ""


def render_main_readme(course, deployed_contents, path_to_content) -> str:
    """The template README in German, then English, with every course and
    assignment title in the section's language where a translation exists."""
    sections = []
    for lang in README_LANGUAGES:
        text = _README_TEXT[lang]
        course_title = _title(course, lang)
        lines = [
            f"# {text['heading'].format(course=course_title)}\n",
            f"{text['intro'].format(count=len(deployed_contents), course=course_title)}\n",
        ]
        if deployed_contents:
            lines += [
                f"## {text['structure']}\n",
                text["columns"],
                "|-------------|---------------------|-------|----------|",
            ]
            for content in deployed_contents:
                if not (content.deployment and content.deployment.example_version):
                    continue
                example = content.deployment.example_version.example
                version = content.deployment.example_version.version_tag
                # Each ancestor path segment by its title where possible.
                path_parts = str(content.path).split('.')
                title_parts = []
                for i, part in enumerate(path_parts):
                    ancestor = path_to_content.get('.'.join(path_parts[:i + 1]))
                    title_parts.append((_title(ancestor, lang) if ancestor else "") or part)
                directory_link = f"[`{example.identifier}/`](./{example.identifier})"
                lines.append(
                    f"| {' / '.join(title_parts)} | {directory_link} | {_title(content, lang)} | {version} |"
                )
            lines.append("")
        else:
            lines.append(f"{text['none']}\n")
        lines += [
            f"## {text['instructions']}\n",
            f"{text['instructions_text']}\n",
            f"## {text['submission']}\n",
            f"{text['submission_text']}\n",
            text["generated"],
        ]
        sections.append("\n".join(lines) + "\n")
    return "\n---\n\n".join(sections)


def generate_main_readme(db: Session, course, template_repo_path: str) -> list:
    """(Re)write the template's README with ALL deployed assignments.

    Includes 'deploying' rows because the README is generated BEFORE the
    final status update of the current run. Returns the deployed/deploying
    contents used, so the caller can gate the git push on them.
    """
    from ...model.course import CourseContent
    from ...model.deployment import CourseContentDeployment
    from ...model.example import ExampleVersion

    course_id = course.id

    all_deployed_contents = db.query(CourseContent).options(
            joinedload(CourseContent.deployment)
                .joinedload(CourseContentDeployment.example_version)
                .joinedload(ExampleVersion.example)
        ).filter(
        CourseContent.course_id == course_id,
        CourseContent.archived_at.is_(None),
        CourseContent.deployment.has(
            CourseContentDeployment.deployment_status.in_(['deployed', 'deploying'])
        )
    ).order_by(CourseContent.path).all()

    logger.info(f"Found {len(all_deployed_contents)} deployed/deploying assignments for README generation")

    path_to_content = {}
    if all_deployed_contents:
        # Fetch all course contents to build complete path hierarchy
        all_contents = db.query(CourseContent).filter(
            CourseContent.course_id == course_id,
            CourseContent.archived_at.is_(None)
        ).all()
        path_to_content = {str(c.path): c for c in all_contents}

    main_readme_path = os.path.join(template_repo_path, "README.md")
    with open(main_readme_path, 'w') as f:
        f.write(render_main_readme(course, all_deployed_contents, path_to_content))

    logger.info(f"Generated main README.md with {len(all_deployed_contents)} deployed assignments (current state)")
    return all_deployed_contents
